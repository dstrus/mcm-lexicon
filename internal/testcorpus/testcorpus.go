// Package testcorpus gives tests their mod lists: small Mod Organizer 2
// instances built in temporary folders for the cases a real list can't
// show, and the real lists themselves, as the snapshots in the repository's
// snapshots folder (PLAN.md §10), which are the main test data.
package testcorpus

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// Instance is an MO2 instance being built. Mods are added from the lowest
// priority up, as they'd be dragged into MO2's list.
type Instance struct {
	t       *testing.T
	Dir     string
	Profile string
	entries []string // modlist.txt's lines below the comment, highest priority first
	plugins []string // plugins.txt's lines; nil for none
	ini     map[string]string
}

// New makes an instance named name (which may hold brackets and
// apostrophes, as real ones do) with the given profiles, the first one
// selected, for Skyrim VR.
func New(t *testing.T, name string, profiles ...string) *Instance {
	t.Helper()
	inst := &Instance{t: t, Dir: filepath.Join(t.TempDir(), name), Profile: profiles[0], ini: map[string]string{"gameName": "Skyrim VR"}}
	for _, sub := range []string{"mods", "overwrite", "profiles"} {
		inst.mkdir(filepath.Join(inst.Dir, sub))
	}
	for _, p := range profiles {
		pdir := filepath.Join(inst.Dir, "profiles", p)
		inst.mkdir(pdir)
		inst.write(filepath.Join(pdir, "modlist.txt"), "# This file was automatically generated by Mod Organizer.\n")
		inst.write(filepath.Join(pdir, "plugins.txt"), "# This file was automatically generated by Mod Organizer.\n")
	}
	inst.writeINI()
	return inst
}

// MO2Instance is New for tests that only need the instance's path.
func MO2Instance(t *testing.T, name string, profiles ...string) string {
	t.Helper()
	return New(t, name, profiles...).Dir
}

// Mod adds a mod above every mod so far, with files by their path under
// the mod (forward slashes).
func (i *Instance) Mod(name string, enabled bool, files map[string]string) {
	i.t.Helper()
	dir := filepath.Join(i.Dir, "mods", name)
	i.mkdir(dir)
	for rel, content := range files {
		i.write(filepath.Join(dir, filepath.FromSlash(rel)), content)
	}
	mark := "+"
	if !enabled {
		mark = "-"
	}
	i.entries = append([]string{mark + name}, i.entries...)
	i.writeModlist()
}

// Separator adds a separator above every mod so far, as MO2 lists them.
func (i *Instance) Separator(name string) {
	i.entries = append([]string{"-" + name + "_separator"}, i.entries...)
	i.writeModlist()
}

// Unmanaged adds a DLC or Creation Club entry, which has no folder.
func (i *Instance) Unmanaged(name string) {
	i.entries = append([]string{"*" + name}, i.entries...)
	i.writeModlist()
}

// Overwrite puts files in the overwrite folder.
func (i *Instance) Overwrite(files map[string]string) {
	i.t.Helper()
	for rel, content := range files {
		i.write(filepath.Join(i.Dir, "overwrite", filepath.FromSlash(rel)), content)
	}
}

// Plugins writes plugins.txt with these lines ("*Name.esp" is active).
func (i *Instance) Plugins(lines ...string) {
	i.t.Helper()
	i.plugins = lines
	i.write(filepath.Join(i.Dir, "profiles", i.Profile, "plugins.txt"), "# This file was automatically generated by Mod Organizer.\n"+strings.Join(lines, "\n")+"\n")
}

// NoPluginsFile removes plugins.txt, as a profile that hasn't been run has none.
func (i *Instance) NoPluginsFile() {
	i.t.Helper()
	i.plugins = nil
	if err := os.Remove(filepath.Join(i.Dir, "profiles", i.Profile, "plugins.txt")); err != nil {
		i.t.Fatal(err)
	}
}

// GamePath names the game folder in ModOrganizer.ini, as MO2 writes it.
func (i *Instance) GamePath(path string) {
	i.ini["gamePath"] = "@ByteArray(" + strings.ReplaceAll(path, `\`, `\\`) + ")"
	i.writeINI()
}

func (i *Instance) writeModlist() {
	i.t.Helper()
	i.write(filepath.Join(i.Dir, "profiles", i.Profile, "modlist.txt"), "# This file was automatically generated by Mod Organizer.\n"+strings.Join(i.entries, "\n")+"\n")
}

func (i *Instance) writeINI() {
	i.t.Helper()
	var b strings.Builder
	b.WriteString("[General]\n")
	b.WriteString("gameName=" + i.ini["gameName"] + "\n")
	if p := i.ini["gamePath"]; p != "" {
		b.WriteString("gamePath=" + p + "\n")
	}
	b.WriteString("selected_profile=@ByteArray(" + i.Profile + ")\n\n[Settings]\nlanguage=en\n")
	i.write(filepath.Join(i.Dir, "ModOrganizer.ini"), b.String())
}

func (i *Instance) mkdir(dir string) {
	i.t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		i.t.Fatal(err)
	}
}

func (i *Instance) write(path, content string) {
	i.t.Helper()
	i.mkdir(filepath.Dir(path))
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		i.t.Fatal(err)
	}
}

// Snapshot is a real list's snapshot, unpacked.
type Snapshot struct {
	Name string // the snapshot folder's name
	Root string // the folder holding mo2/ and SNAPSHOT.md
	Dir  string // the mo2/ instance
}

// Snapshots is every unpacked snapshot in the snapshots folder: the one
// LEXICON_SNAPSHOTS names, or the repository's. A test that gets none is
// skipped, since the snapshots hold other authors' files and aren't in
// the repository.
func Snapshots(t *testing.T) []Snapshot {
	t.Helper()
	dir := os.Getenv("LEXICON_SNAPSHOTS")
	if dir == "" {
		root, ok := repoRoot()
		if !ok {
			t.Skip("not inside the repository, and LEXICON_SNAPSHOTS isn't set")
		}
		dir = filepath.Join(root, "snapshots")
	}
	entries, _ := os.ReadDir(dir)
	var out []Snapshot
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		root := filepath.Join(dir, e.Name())
		if _, err := os.Stat(filepath.Join(root, "mo2", "ModOrganizer.ini")); err == nil {
			out = append(out, Snapshot{Name: e.Name(), Root: root, Dir: filepath.Join(root, "mo2")})
		}
	}
	if len(out) == 0 {
		t.Skipf("no unpacked snapshots in %s", dir)
	}
	return out
}

// repoRoot is the folder holding go.mod, found upward from the test's
// working directory (its package's folder).
func repoRoot() (string, bool) {
	dir, err := os.Getwd()
	if err != nil {
		return "", false
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, true
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", false
		}
		dir = parent
	}
}
