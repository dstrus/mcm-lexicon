// Package testcorpus gives tests their mod lists: small Mod Organizer 2
// instances built in temporary folders for the cases a real list can't
// show, and the real lists themselves, as the snapshots in the repository's
// snapshots folder (PLAN.md §10), which are the main test data.
package testcorpus

import (
	"bytes"
	"compress/zlib"
	"encoding/binary"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// Instance is an MO2 instance being built. Mods are added from the lowest
// priority up, as they'd be dragged into MO2's list.
type Instance struct {
	t       *testing.T
	Dir     string
	Profile string
	entries []string // modlist.txt's lines below the comment, highest priority first
	plugins []string // plugins.txt's lines; nil for none
	ini     map[string]string
}

// New makes an instance named name (which may hold brackets and
// apostrophes, as real ones do) with the given profiles, the first one
// selected, for Skyrim VR.
func New(t *testing.T, name string, profiles ...string) *Instance {
	t.Helper()
	inst := &Instance{t: t, Dir: filepath.Join(t.TempDir(), name), Profile: profiles[0], ini: map[string]string{"gameName": "Skyrim VR"}}
	for _, sub := range []string{"mods", "overwrite", "profiles"} {
		inst.mkdir(filepath.Join(inst.Dir, sub))
	}
	for _, p := range profiles {
		pdir := filepath.Join(inst.Dir, "profiles", p)
		inst.mkdir(pdir)
		inst.write(filepath.Join(pdir, "modlist.txt"), "# This file was automatically generated by Mod Organizer.\n")
		inst.write(filepath.Join(pdir, "plugins.txt"), "# This file was automatically generated by Mod Organizer.\n")
	}
	inst.writeINI()
	return inst
}

// MO2Instance is New for tests that only need the instance's path.
func MO2Instance(t *testing.T, name string, profiles ...string) string {
	t.Helper()
	return New(t, name, profiles...).Dir
}

// Mod adds a mod above every mod so far, with files by their path under
// the mod (forward slashes).
func (i *Instance) Mod(name string, enabled bool, files map[string]string) {
	i.t.Helper()
	dir := filepath.Join(i.Dir, "mods", name)
	i.mkdir(dir)
	for rel, content := range files {
		i.write(filepath.Join(dir, filepath.FromSlash(rel)), content)
	}
	mark := "+"
	if !enabled {
		mark = "-"
	}
	i.entries = append([]string{mark + name}, i.entries...)
	i.writeModlist()
}

// Separator adds a separator above every mod so far, as MO2 lists them.
func (i *Instance) Separator(name string) {
	i.entries = append([]string{"-" + name + "_separator"}, i.entries...)
	i.writeModlist()
}

// Unmanaged adds a DLC or Creation Club entry, which has no folder.
func (i *Instance) Unmanaged(name string) {
	i.entries = append([]string{"*" + name}, i.entries...)
	i.writeModlist()
}

// Overwrite puts files in the overwrite folder.
func (i *Instance) Overwrite(files map[string]string) {
	i.t.Helper()
	for rel, content := range files {
		i.write(filepath.Join(i.Dir, "overwrite", filepath.FromSlash(rel)), content)
	}
}

// Plugins writes plugins.txt with these lines ("*Name.esp" is active).
func (i *Instance) Plugins(lines ...string) {
	i.t.Helper()
	i.plugins = lines
	i.write(filepath.Join(i.Dir, "profiles", i.Profile, "plugins.txt"), "# This file was automatically generated by Mod Organizer.\n"+strings.Join(lines, "\n")+"\n")
}

// NoPluginsFile removes plugins.txt, as a profile that hasn't been run has none.
func (i *Instance) NoPluginsFile() {
	i.t.Helper()
	i.plugins = nil
	if err := os.Remove(filepath.Join(i.Dir, "profiles", i.Profile, "plugins.txt")); err != nil {
		i.t.Fatal(err)
	}
}

// GamePath names the game folder in ModOrganizer.ini, as MO2 writes it.
func (i *Instance) GamePath(path string) {
	i.ini["gamePath"] = "@ByteArray(" + strings.ReplaceAll(path, `\`, `\\`) + ")"
	i.writeINI()
}

func (i *Instance) writeModlist() {
	i.t.Helper()
	i.write(filepath.Join(i.Dir, "profiles", i.Profile, "modlist.txt"), "# This file was automatically generated by Mod Organizer.\n"+strings.Join(i.entries, "\n")+"\n")
}

func (i *Instance) writeINI() {
	i.t.Helper()
	var b strings.Builder
	b.WriteString("[General]\n")
	b.WriteString("gameName=" + i.ini["gameName"] + "\n")
	if p := i.ini["gamePath"]; p != "" {
		b.WriteString("gamePath=" + p + "\n")
	}
	b.WriteString("selected_profile=@ByteArray(" + i.Profile + ")\n\n[Settings]\nlanguage=en\n")
	i.write(filepath.Join(i.Dir, "ModOrganizer.ini"), b.String())
}

func (i *Instance) mkdir(dir string) {
	i.t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		i.t.Fatal(err)
	}
}

func (i *Instance) write(path, content string) {
	i.t.Helper()
	i.mkdir(filepath.Dir(path))
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		i.t.Fatal(err)
	}
}

// Snapshot is a real list's snapshot, unpacked.
type Snapshot struct {
	Name string // the snapshot folder's name
	Root string // the folder holding mo2/ and SNAPSHOT.md
	Dir  string // the mo2/ instance
}

// Snapshots is every unpacked snapshot in the snapshots folder: the one
// LEXICON_SNAPSHOTS names, or the repository's. A test that gets none is
// skipped, since the snapshots hold other authors' files and aren't in
// the repository.
func Snapshots(t *testing.T) []Snapshot {
	t.Helper()
	dir := os.Getenv("LEXICON_SNAPSHOTS")
	if dir == "" {
		root, ok := repoRoot()
		if !ok {
			t.Skip("not inside the repository, and LEXICON_SNAPSHOTS isn't set")
		}
		dir = filepath.Join(root, "snapshots")
	}
	entries, _ := os.ReadDir(dir)
	var out []Snapshot
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		root := filepath.Join(dir, e.Name())
		if _, err := os.Stat(filepath.Join(root, "mo2", "ModOrganizer.ini")); err == nil {
			out = append(out, Snapshot{Name: e.Name(), Root: root, Dir: filepath.Join(root, "mo2")})
		}
	}
	if len(out) == 0 {
		t.Skipf("no unpacked snapshots in %s", dir)
	}
	return out
}

// repoRoot is the folder holding go.mod, found upward from the test's
// working directory (its package's folder).
func repoRoot() (string, bool) {
	dir, err := os.Getwd()
	if err != nil {
		return "", false
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, true
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", false
		}
		dir = parent
	}
}

// Quest is a quest with one script attached, for Plugin.
type Quest struct {
	EditorID string
	Script   string
	ModName  string   // the script's ModName property; "" leaves it out
	Pages    []string // its Pages property; nil leaves it out
	FormID   uint32   // 0 for the plugin's own next one, 0x800 on
}

// Plugin is the bytes of a minimal plugin holding the quests, as the
// Creation Kit writes them (VMAD version 5, object format 2).
func Plugin(quests ...Quest) string { return PluginWith(nil, quests...) }

// PluginWith is Plugin with masters, which a quest's FormID counts in its
// first byte: an override of a master's quest gives that master's index.
func PluginWith(masters []string, quests ...Quest) string {
	le := func(v any) []byte {
		var b bytes.Buffer
		binary.Write(&b, binary.LittleEndian, v)
		return b.Bytes()
	}
	wstr := func(s string) []byte { return append(le(uint16(len(s))), s...) }
	sub := func(typ string, data []byte) []byte {
		return append(append([]byte(typ), le(uint16(len(data)))...), data...)
	}
	record := func(typ string, data []byte) []byte {
		return append(append(append([]byte(typ), le(uint32(len(data)))...), make([]byte, 16)...), data...)
	}
	var body []byte
	for i, q := range quests {
		var props [][]byte
		if q.ModName != "" {
			props = append(props, append(append(wstr("ModName"), 2, 1), wstr(q.ModName)...))
		}
		if q.Pages != nil {
			p := append(append(wstr("Pages"), 12, 1), le(uint32(len(q.Pages)))...)
			for _, page := range q.Pages {
				p = append(p, wstr(page)...)
			}
			props = append(props, p)
		}
		v := append(append(append(append(le(int16(5)), le(int16(2))...), le(uint16(1))...), wstr(q.Script)...), 0)
		v = append(v, le(uint16(len(props)))...)
		for _, p := range props {
			v = append(v, p...)
		}
		data := append(sub("EDID", append([]byte(q.EditorID), 0)), sub("VMAD", v)...)
		rec := record("QUST", data)
		id := q.FormID
		if id == 0 {
			id = uint32(len(masters))<<24 | uint32(0x800+i)
		}
		binary.LittleEndian.PutUint32(rec[12:], id)
		body = append(body, rec...)
	}
	header := sub("HEDR", make([]byte, 12))
	for _, m := range masters {
		header = append(header, sub("MAST", append([]byte(m), 0))...)
	}
	file := record("TES4", header)
	if len(body) > 0 {
		file = append(file, "GRUP"...)
		file = append(file, le(uint32(24+len(body)))...)
		file = append(file, "QUST"...)
		file = append(file, make([]byte, 12)...)
		file = append(file, body...)
	}
	return string(file)
}

// Compiled is the bytes of a minimal compiled script (.pex) named name,
// extending parent, with no functions; strs go into its string table, as
// the literals of the source it was compiled from would.
func Compiled(name, parent string, strs ...string) string {
	var b bytes.Buffer
	be := func(v any) { binary.Write(&b, binary.BigEndian, v) }
	ws := func(s string) { be(uint16(len(s))); b.WriteString(s) }
	table := append([]string{name, parent, ""}, strs...)
	be(uint32(0xFA57C0DE))
	b.Write([]byte{3, 2})
	be(uint16(1))
	b.Write(make([]byte, 8))
	ws(name + ".psc")
	ws("user")
	ws("machine")
	be(uint16(len(table)))
	for _, s := range table {
		ws(s)
	}
	b.WriteByte(0) // no debug info
	be(uint16(0))  // user flags
	be(uint16(1))  // objects
	be(uint16(0))  // its name
	be(uint32(4 + 2 + 2 + 4 + 2 + 2 + 2 + 2))
	be(uint16(1)) // parent
	be(uint16(2)) // documentation
	be(uint32(0)) // user flags
	be(uint16(2)) // auto state
	be(uint16(0)) // variables
	be(uint16(0)) // properties
	be(uint16(0)) // states
	return b.String()
}

// ArchiveOptions is how Archive packs its files.
type ArchiveOptions struct {
	Version    int             // 104 (zlib) or 105 (LZ4); 105 when 0
	Compressed bool            // compress files by default
	Flip       map[string]bool // paths whose compression is the opposite of the default
	EmbedNames bool            // start each file's data with its full path
}

// Archive is the bytes of a Bethesda archive holding files, by their
// paths with forward slashes. LZ4 is written as uncompressed literals,
// which any reader must handle, so the reader's own tests cover real
// compressed data.
func Archive(opts ArchiveOptions, files map[string]string) string {
	version := uint32(opts.Version)
	if version == 0 {
		version = 105
	}
	byFolder := map[string][]string{}
	for p := range files {
		dir, name := path.Split(strings.ToLower(p))
		byFolder[strings.Trim(dir, "/")] = append(byFolder[strings.Trim(dir, "/")], name)
	}
	var folders []string
	for f := range byFolder {
		folders = append(folders, f)
		sort.Strings(byFolder[f])
	}
	sort.Strings(folders)
	flags := uint32(0x1 | 0x2)
	if opts.Compressed {
		flags |= 0x4
	}
	if opts.EmbedNames {
		flags |= 0x100
	}
	folderRecord := 16
	if version == 105 {
		folderRecord = 24
	}
	var names bytes.Buffer
	folderNames := 0
	for _, f := range folders {
		folderNames += len(f) + 1
		for _, n := range byFolder[f] {
			names.WriteString(n)
			names.WriteByte(0)
		}
	}
	// The data follows the header, the folder records, the folders' names
	// and file records, and the file names.
	dataAt := 36 + len(folders)*folderRecord + len(folders) + folderNames + len(files)*16 + names.Len()
	var data, records bytes.Buffer
	le := func(b *bytes.Buffer, v any) { binary.Write(b, binary.LittleEndian, v) }
	var folderRecs bytes.Buffer
	for _, f := range folders {
		le(&folderRecs, uint64(0)) // hash: unread
		le(&folderRecs, uint32(len(byFolder[f])))
		if version == 105 {
			le(&folderRecs, uint32(0))
			le(&folderRecs, uint64(0))
		} else {
			le(&folderRecs, uint32(0))
		}
		records.WriteByte(byte(len(f) + 1))
		records.WriteString(f)
		records.WriteByte(0)
		for _, n := range byFolder[f] {
			full := n
			if f != "" {
				full = f + "/" + n
			}
			var content string
			for p, c := range files {
				if strings.EqualFold(p, full) {
					content = c
				}
			}
			compressed := opts.Compressed != opts.Flip[full]
			var stored bytes.Buffer
			if opts.EmbedNames {
				embedded := strings.ReplaceAll(full, "/", `\`)
				stored.WriteByte(byte(len(embedded)))
				stored.WriteString(embedded)
			}
			if compressed {
				le(&stored, uint32(len(content)))
				if version == 104 {
					z := zlib.NewWriter(&stored)
					z.Write([]byte(content))
					z.Close()
				} else {
					stored.Write(lz4Literals(content))
				}
			} else {
				stored.WriteString(content)
			}
			size := uint32(stored.Len())
			if opts.Flip[full] {
				size |= 0x40000000
			}
			le(&records, uint64(0))
			le(&records, size)
			le(&records, uint32(dataAt+data.Len()))
			data.Write(stored.Bytes())
		}
	}
	var b bytes.Buffer
	b.WriteString("BSA\x00")
	for _, v := range []uint32{version, 36, flags, uint32(len(folders)), uint32(len(files)), uint32(folderNames), uint32(names.Len())} {
		le(&b, v)
	}
	le(&b, uint32(0)) // file flags and padding
	b.Write(folderRecs.Bytes())
	b.Write(records.Bytes())
	b.Write(names.Bytes())
	b.Write(data.Bytes())
	return b.String()
}

// lz4Literals is an LZ4 frame holding s as one block of literals.
func lz4Literals(s string) []byte {
	var block bytes.Buffer
	n := len(s)
	if n < 15 {
		block.WriteByte(byte(n << 4))
	} else {
		block.WriteByte(0xF0)
		for n -= 15; n >= 255; n -= 255 {
			block.WriteByte(255)
		}
		block.WriteByte(byte(n))
	}
	block.WriteString(s)
	var b bytes.Buffer
	binary.Write(&b, binary.LittleEndian, uint32(0x184D2204))
	b.Write([]byte{0x60, 0x40, 0x82}) // version 1, independent blocks; 64 KB blocks; header checksum (unread)
	binary.Write(&b, binary.LittleEndian, uint32(block.Len()))
	b.Write(block.Bytes())
	binary.Write(&b, binary.LittleEndian, uint32(0))
	return b.Bytes()
}
