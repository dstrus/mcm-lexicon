// Package testcorpus builds small mod lists in temporary folders for tests:
// Mod Organizer 2 instances with the files MCM Lexicon reads. The real
// snapshots of the author's lists (PLAN.md §10) are read by the opt-in
// acceptance tests, which come with scanning.
package testcorpus

import (
	"os"
	"path/filepath"
	"testing"
)

// MO2Instance makes an MO2 instance named name (which may hold brackets
// and apostrophes, as real ones do) with the given profiles, the first one
// selected, for Skyrim VR. It returns the instance's path.
func MO2Instance(t *testing.T, name string, profiles ...string) string {
	t.Helper()
	dir := filepath.Join(t.TempDir(), name)
	for _, sub := range []string{"mods", "overwrite", "profiles"} {
		if err := os.MkdirAll(filepath.Join(dir, sub), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	ini := "[General]\ngameName=Skyrim VR\nselected_profile=@ByteArray(" + profiles[0] + ")\n\n[Settings]\nlanguage=en\n"
	if err := os.WriteFile(filepath.Join(dir, "ModOrganizer.ini"), []byte(ini), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, p := range profiles {
		pdir := filepath.Join(dir, "profiles", p)
		if err := os.MkdirAll(pdir, 0o755); err != nil {
			t.Fatal(err)
		}
		for _, f := range []string{"modlist.txt", "plugins.txt"} {
			if err := os.WriteFile(filepath.Join(pdir, f), []byte("# This file was automatically generated by Mod Organizer.\n"), 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	return dir
}
