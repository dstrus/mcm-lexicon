// The UI's copy lives in src/lib/copy/en.yaml; this turns it into the typed
// module the components import (src/lib/copy/messages.ts, generated and
// never edited), so a missing or misspelled message fails the type check.
// Vite runs it on every build and whenever the file changes during
// `make dev`; `npm run check` runs it first (`node copy.ts`).
//
// In the YAML, a group is a map of messages, and a message is:
// - text, with {name} placeholders that become its parameters;
// - or forms chosen by a number, `one:` and `other:` (and `zero:` when
//   "none" reads better), each of which may use {count}.
// A message with placeholders is a function that also carries its text as
// .text, for lib/copy/Fill.svelte to fill a placeholder with markup.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
export const source = join(here, 'src/lib/copy/en.yaml');
const output = join(here, 'src/lib/copy/messages.ts');

const identifier = /^[a-z][A-Za-z0-9]*$/;
const forms = ['zero', 'one', 'other'];

class CopyError extends Error {}

// A message's forms when it's a map of them, as opposed to a group.
function isForms(v: unknown): v is Record<string, string> {
	if (!v || typeof v !== 'object' || Array.isArray(v)) return false;
	const keys = Object.keys(v);
	return keys.includes('other') && keys.every((k) => forms.includes(k) && typeof (v as Record<string, unknown>)[k] === 'string');
}

function placeholders(text: string): string[] {
	return [...new Set([...text.matchAll(/\{([A-Za-z][A-Za-z0-9]*)\}/g)].map((m) => m[1]!))];
}

// literal writes text as a template literal, with its placeholders filled
// from p.
function literal(text: string): string {
	const escaped = text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
	return '`' + escaped.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_, name) => (name === 'count' ? '${n(p.count)}' : `\${p.${name}}`)) + '`';
}

function params(names: string[]): string {
	return `{ ${names.map((n) => `${n}: ${n === 'count' ? 'number' : 'string | number'}`).join('; ')} }`;
}

function message(path: string, v: unknown): string {
	if (typeof v === 'string') {
		const names = placeholders(v);
		if (!names.length) return JSON.stringify(v);
		return `msg((p: ${params(names)}) => ${literal(v)}, ${JSON.stringify(v)})`;
	}
	if (isForms(v)) {
		const names = [...new Set(['count', ...Object.values(v).flatMap(placeholders)])];
		const pick = [
			v.zero !== undefined ? `p.count === 0 ? ${literal(v.zero)}` : '',
			v.one !== undefined ? `p.count === 1 ? ${literal(v.one)}` : '',
			literal(v.other!)
		].filter(Boolean);
		return `(p: ${params(names)}) => (${pick.join(' : ')})`;
	}
	throw new CopyError(`${path} must be text, or one:/other: forms`);
}

function group(path: string, v: unknown, indent: string): string {
	if (!v || typeof v !== 'object' || Array.isArray(v)) throw new CopyError(`${path || 'The file'} must be a group of messages`);
	const lines = Object.entries(v as Record<string, unknown>).map(([key, value]) => {
		const at = path ? `${path}.${key}` : key;
		if (!identifier.test(key)) throw new CopyError(`${at}: a name is lowerCamelCase letters and digits`);
		const body = typeof value === 'string' || isForms(value) ? message(at, value) : group(at, value, indent + '\t');
		return `${indent}\t${key}: ${body}`;
	});
	return `{\n${lines.join(',\n')}\n${indent}}`;
}

// generate writes messages.ts from en.yaml, when it would change.
export function generate(): void {
	const doc = parse(readFileSync(source, 'utf8'));
	const out = `// Generated by web/copy.ts from en.yaml. Edit en.yaml, not this.
const n = (x: number) => x.toLocaleString();
const msg = <F extends (p: never) => string>(f: F, text: string) => Object.assign(f, { text });

export const m = ${group('', doc, '')} as const;
`;
	if (!existsSync(output) || readFileSync(output, 'utf8') !== out) writeFileSync(output, out);
}

// copy is the Vite plugin: it generates before a build, and again whenever
// en.yaml changes during development.
export function copy(): Plugin {
	return {
		name: 'lexicon-copy',
		buildStart() {
			generate();
		},
		configureServer(server) {
			server.watcher.add(source);
			server.watcher.on('change', (file) => {
				if (file !== source) return;
				try {
					generate();
				} catch (e) {
					server.config.logger.error(`en.yaml: ${e instanceof Error ? e.message : String(e)}`);
				}
			});
		}
	};
}

// `node copy.ts` generates once, for svelte-check.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	try {
		generate();
	} catch (e) {
		console.error(`en.yaml: ${e instanceof Error ? e.message : String(e)}`);
		process.exit(1);
	}
}
